// Makes the projects of the MC protocol integration tests (specs/017-driver-mc T031) and the map of
// the simulator they read (tools/mc-sim/maps/it-all-types.json). The result is committed; run
// `node tests/driver-it/make-mc-projects.mjs` after a change of the Tags. The rig is
// tests/driver-it/compose-mc.yaml (simulator `sim`, TCP and UDP port 5007), the runner
// tools/driver-it-mc.ps1, the scenarios tests/driver-it/mc-it.mjs.
//
//   mc-all-types: three channels to the same simulator, one field device each:
//     plc-a  3E binary over TCP: every device and type, a block above 960 words (R), 200 scattered
//            D words (two Random Reads), the writable Tags (device write.registerBit rmw)
//     plc-b  4E ASCII over TCP: every device and type, the R block, two writable Tags
//     plc-c  3E binary over UDP: every device and type
//   bench-500-mc: 500 Tags of normal group 1 s on one 3E binary channel (tools/mc-sim/maps/bench-500.json):
//     400 D words, 80 M bits and 20 FLOAT32, all changing every second.
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const V = '1.1.0';

const write = (file, obj) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, JSON.stringify(obj, null, 2) + '\n');
};

const wave = {
  id: 'A.WAVE',
  kind: 'simulation',
  type: 'FLOAT32',
  sim: { kind: 'ramp', from: 0, to: 100, periodMs: 10000 },
};

function project(name, id, channels, tags) {
  const dir = join(here, 'projects', name);
  rmSync(dir, { recursive: true, force: true });
  write(join(dir, 'project.json'), {
    format: 'matscada-project',
    schemaVersion: V,
    projectId: id,
    projectName: `Kiểm thử driver MC: ${name}`,
    projectVersion: '0.1.0',
    minRuntimeVersion: '1.1.0',
    entryScreen: 'main',
    screens: ['main'],
    tagFile: 'tags.json',
    connectionFile: 'connections.json',
    maxClients: 10,
  });
  write(join(dir, 'connections.json'), {
    schemaVersion: V,
    scanGroups: { fast: 250, normal: 1000, slow: 5000 },
    channels,
  });
  write(join(dir, 'tags.json'), { schemaVersion: V, tags: [wave, ...tags] });
  write(join(dir, 'screens', 'main.screen.json'), {
    schemaVersion: V,
    id: 'main',
    name: 'Main',
    kind: 'screen',
    size: { width: 1280, height: 720 },
    fitMode: 'contain',
    items: [
      {
        id: 'card_wave',
        type: 'widget',
        widget: 'card',
        x: 20,
        y: 20,
        width: 220,
        height: 110,
        props: { label: 'Sóng' },
        tags: { value: 'A.WAVE' },
      },
    ],
  });
}

const channel = (id, name, device, mc, more = {}) => ({
  id,
  name,
  kind: 'mc',
  tcp: { host: 'sim', port: 5007, connectTimeoutMs: 1000, reconnectMaxS: 4 },
  ...(mc ? { mc } : {}),
  devices: [{ id: device, name: `PLC giả lập ${id}`, timeoutMs: 500, ...more }],
});

const ext = (id, type, device, address, more = {}, source = {}) => ({
  id,
  kind: 'external',
  type,
  source: { device, address, ...source },
  ...more,
});

