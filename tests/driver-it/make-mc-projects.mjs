// R0, R15, ... R1995: one stretch of 1997 words, more than two Batch Reads of 960
const R_BLOCK = [];
for (let k = 0; k * 15 <= 1995; k++) R_BLOCK.push({ at: k * 15, value: k * 7 - 300 });
// D4000, D4020, ... D7980: 200 single words further apart than maxGapWords (16): Random Read
const D_SCATTER = [];
for (let k = 0; k < 200; k++) D_SCATTER.push({ at: 4000 + 20 * k, value: k - 100 });
for (const r of R_BLOCK) map.devices.R.values.push({ at: r.at, type: 'INT16', value: r.value });
for (const d of D_SCATTER) map.devices.D.values.push({ at: d.at, type: 'INT16', value: d.value });

