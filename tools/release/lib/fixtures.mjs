import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

function put(root, rel, text) {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
}

/**
 * Tạo repo mẫu ở `root`.
 * @param {string} root
 * @param {{ extraNpm?: Record<string, object>, extraCrates?: Array<{name:string,version:string,license:string|null}> }} [opt]
 */
export function makeFixtureRepo(root, opt = {}) {
  const packages = {
    '': { name: 'fixture', version: '0.0.0', workspaces: ['packages/*'] },
    'packages/foo': { name: '@mat/foo', version: '0.1.0' },
    'node_modules/@mat/foo': { resolved: 'packages/foo', link: true },
    'node_modules/lit': {
      version: '3.3.3',
      resolved: 'https://registry.npmjs.org/lit/-/lit-3.3.3.tgz',
      integrity: 'sha512-' + Buffer.alloc(64, 1).toString('base64'),
      license: 'BSD-3-Clause',
    },
    'node_modules/@lit/reactive-element': { version: '2.1.2', license: 'BSD-3-Clause' },
    'node_modules/nolic': { version: '1.0.0' },
    'node_modules/png-js': { version: '1.1.0' },
    'node_modules/devtool': { version: '2.0.0', dev: true, license: 'MPL-2.0' },
    'node_modules/other/node_modules/lit': { version: '3.3.3', license: 'BSD-3-Clause' },
    'node_modules/other': { version: '1.0.0', license: '(MIT AND Zlib)' },
    ...opt.extraNpm,
  };
  put(
    root,
    'package-lock.json',
    JSON.stringify({ name: 'fixture', lockfileVersion: 3, packages }, null, 2),
  );
  put(root, 'node_modules/nolic/package.json', JSON.stringify({ name: 'nolic', license: 'ISC' }));

  const crates = [
    { name: 'mat-studio', version: '0.8.0', source: null, license: null },
    { name: 'serde', version: '1.0.228', license: 'MIT OR Apache-2.0' },
    { name: 'dual', version: '0.3.0', license: 'MIT OR Apache-2.0 OR LGPL-2.1-or-later' },
    { name: 'unicode-ident', version: '1.0.0', license: '(MIT OR Apache-2.0) AND Unicode-3.0' },
    ...(opt.extraCrates ?? []),
  ];
  const lock = ['# This file is automatically @generated by Cargo.', 'version = 4', ''];
  for (const c of crates) {
    lock.push('[[package]]', `name = "${c.name}"`, `version = "${c.version}"`);
    if (c.source !== null) {
      lock.push(
        'source = "registry+https://github.com/rust-lang/crates.io-index"',
        `checksum = "${'ab'.repeat(32)}"`,
      );
    }
    lock.push('');
  }
  put(root, 'apps/studio/src-tauri/Cargo.lock', lock.join('\n'));
  const meta = {
    packages: crates.map((c) => ({
      name: c.name,
      version: c.version,
      license: c.license,
      source: c.source === null ? null : 'registry+https://github.com/rust-lang/crates.io-index',
    })),
  };
  put(root, 'cargo-metadata.json', JSON.stringify(meta));

  put(
    root,
    'third_party/LICENSES.md',
    [
      '# Thư viện bên thứ ba (vendored)',
      '',
      '| Thư viện | Phiên bản | License | Thư mục | Dùng ở | Nguồn |',
      '|---|---|---|---|---|---|',
      '| CivetWeb | 1.16 | MIT | `civetweb/` (`LICENSE.md`) | `mat-runtime` | https://github.com/civetweb/civetweb |',
      '| GoogleTest | 1.15.2 | BSD-3-Clause | `googletest/` (`LICENSE`) | **chỉ test** trên x64 | https://github.com/google/googletest |',
      '| SQLite | 3.54.0 | Public domain | `sqlite/` (`sqlite3.c`) | `mat-runtime` | https://www.sqlite.org/2026/sqlite-amalgamation-3540000.zip, SHA3-256 `' +
        'cd'.repeat(32) +
        '` |',
      '| Mbed TLS | 3.6.7 (2026-07-07), nhánh LTS | Apache-2.0 (bản phát hành: Apache-2.0 OR GPL-2.0-or-later; chọn Apache-2.0) | `mbedtls/` | `mat-runtime` | https://example.invalid/mbedtls-3.6.7.tar.bz2, SHA-256 `' +
        'ef'.repeat(32) +
        '` |',
      '',
      '## Ghi đè license cho công cụ phát hành',
      '',
      '| Thành phần | License | Lý do |',
      '|---|---|---|',
      '| `npm:png-js@1.1.0` | MIT | package.json không khai `license`; tệp `LICENSE` của gói là MIT |',
      '',
    ].join('\n'),
  );
}
